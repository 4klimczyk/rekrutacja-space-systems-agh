import copy
import datetime
from math import exp
from rocketpy import (
    CylindricalTank,
    Environment,
    Flight,
    Fluid,
    Function,
    LiquidMotor,
    MassFlowRateBasedTank,
    Rocket,
)

# Ponte de Sor, Portugalia
env = Environment(latitude=39.2494, longitude=-8.0089, elevation=121)
tomorrow = datetime.date.today() + datetime.timedelta(days=1)
env.set_date((tomorrow.year, tomorrow.month, tomorrow.day, 12))
env.set_atmospheric_model(type="Forecast", file="GFS")


oxidizer_liq = Fluid(name="N2O_l", density=1220)
oxidizer_gas = Fluid(name="N2O_g", density=1.9277)
fuel_liq = Fluid(name="ethanol_l", density=789)
fuel_gas = Fluid(name="ethanol_g", density=1.59)

# Zbiornik utleniacza
ox_tank_shape = CylindricalTank(
    radius=0.065, height=0.85, spherical_caps=True
)
# Zbiornik paliwa
fuel_tank_shape = CylindricalTank(
    radius=0.065, height=0.45, spherical_caps=True
)

# burn_time = 7.5
burn_time = 7.3

oxidizer_tank = MassFlowRateBasedTank(
    name="oxidizer tank",
    geometry=ox_tank_shape,
    flux_time=burn_time,
    initial_liquid_mass=11.501,
    initial_gas_mass=0.001,
    liquid_mass_flow_rate_in=0,
    liquid_mass_flow_rate_out=lambda t: (11.5 / burn_time)
    * (1.1 - 0.2 * (t / burn_time)),
    gas_mass_flow_rate_in=0,
    gas_mass_flow_rate_out=0,
    liquid=oxidizer_liq,
    gas=oxidizer_gas,
)

fuel_tank = MassFlowRateBasedTank(
    name="fuel tank",
    geometry=fuel_tank_shape,
    flux_time=burn_time,
    initial_liquid_mass=3.001,
    initial_gas_mass=0.001,
    liquid_mass_flow_rate_in=0,
    liquid_mass_flow_rate_out=lambda t: (3.0 / burn_time)
    * (1.1 - 0.2 * (t / burn_time)),
    gas_mass_flow_rate_in=0,
    gas_mass_flow_rate_out=0,
    liquid=fuel_liq,
    gas=fuel_gas,
)


motor_L9 = LiquidMotor(
    thrust_source=lambda t: 4000 - 40 * t,
    dry_mass=6.5,
    dry_inertia=(0.35, 0.35, 0.015),
    nozzle_radius=0.045,
    center_of_dry_mass_position=0.35,
    nozzle_position=0,
    burn_time=burn_time,
    coordinate_system_orientation="nozzle_to_combustion_chamber",
)
motor_L9.add_tank(tank=oxidizer_tank, position=1.4)
motor_L9.add_tank(tank=fuel_tank, position=0.6)


rocket_L9 = Rocket(
    radius=0.075,
    mass=15.5,
    inertia=(18.5, 18.5, 0.08),
    power_off_drag="powerOffDragCurve.csv",
    power_on_drag="powerOnDragCurve.csv",
    center_of_mass_without_motor=1.65,
    coordinate_system_orientation="tail_to_nose",
)

socket_L9 = rocket_L9.add_motor(motor_L9, position=-1.60)

rocket_L9.set_rail_buttons(
    upper_button_position=0.20,
    lower_button_position=-0.90,
    angular_position=45,
)

nose_cone = rocket_L9.add_nose(
    length=0.75, kind="von karman", position=1.60
)


fin_set = rocket_L9.add_trapezoidal_fins(
    n=4,
    # root_chord=0.260,
    # tip_chord=0.100,
    # span=0.135,
    root_chord=0.180,
    tip_chord=0.070,
    span=0.105,
    # position=-1.35,
    position=-0.675,
    cant_angle=0.0,
    airfoil=("NACA0012-radians.txt", "radians"),
)

tail = rocket_L9.add_tail(
    top_radius=0.075, bottom_radius=0.055, length=0.080, position=-1.52
)


drogue = rocket_L9.add_parachute(
    name="drogue",
    # cd_s=0.50,
    cd_s=.60,
    trigger="apogee",
    sampling_rate=105,
    lag=1.5,
)

main = rocket_L9.add_parachute(
    name="main",
    cd_s=9.50,
    trigger=450,  # >= 450 m AGL
    sampling_rate=105,
    lag=1.5,
)


flight_L9 = Flight(
    rocket=rocket_L9,
    environment=env,
    rail_length=12.0,
    inclination=84,
    heading=133,
)


print("\n" + "=" * 45)
print("     WYNIKI SYMULACJI - EUROC LIQUID 9 KM")
print("=" * 45)
print(f"Apogeum (AGL):          {flight_L9.apogee - env.elevation:.1f} m")
print(f"Prędkość z rampy:       {flight_L9.out_of_rail_velocity:.2f} m/s (Min: >30 m/s)")
print(f"Maksymalna prędkość:    {flight_L9.max_speed:.1f} m/s (Mach {flight_L9.max_mach_number:.2f})")
print(f"Czas do apogeum:        {flight_L9.apogee_time:.1f} s")
drogue_trigger_time = flight_L9.parachute_events[0][0]
speed_under_drogue = flight_L9.speed(drogue_trigger_time + 5.0)

print(f"Prędkość pod drogue:    {speed_under_drogue:.1f} m/s (Wymóg: 23-46 m/s)")
print(f"Prędkość przyziemienia: {abs(flight_L9.impact_velocity):.2f} m/s (Wymóg: <9 m/s)")
print(f"Zapas stabilności (0s): {rocket_L9.static_margin(0):.2f} cal")
print(f"Zapas z rampy:          {rocket_L9.static_margin(flight_L9.out_of_rail_time):.2f} cal (Wymóg: >=1.5 cal)")
print("=" * 45)

# flight_L9.plots.trajectory_3d()
# flight_L9.speed.plot()
rocket_L9.plots.static_margin()
rocket_L9.draw()


motor_L9.info()


